from abc import ABC, abstractmethod
from typing import Any

class BrokerInterface(ABC):
    """Broker-agnostic contract for future broker adapters.

    `tag` is an optional client order reference. OrderManager uses it to find
    an order on the broker after an ambiguous submission (e.g. a timeout)
    instead of resubmitting.
    """

    @abstractmethod
    def connect(self) -> None: ...
    @abstractmethod
    def disconnect(self) -> None: ...
    @abstractmethod
    def is_connected(self) -> bool: ...
    @abstractmethod
    def get_ltp(self, symbol: str) -> float: ...
    @abstractmethod
    def get_account(self) -> dict[str, Any]: ...
    @abstractmethod
    def get_positions(self) -> list[dict[str, Any]]: ...
    @abstractmethod
    def get_orders(self) -> list[dict[str, Any]]: ...
    @abstractmethod
    def place_order(self, symbol: str, side: str, quantity: int,
                    order_type: str, price: float | None = None,
                    tag: str | None = None) -> str: ...
    @abstractmethod
    def modify_order(self, order_id: str, **kwargs: Any) -> None: ...
    @abstractmethod
    def cancel_order(self, order_id: str) -> None: ...
    @abstractmethod
    def close_position(self, symbol: str) -> str: ...
